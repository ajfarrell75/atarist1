// tick function

// tick function for smaller objects with no occlusion maps - allow them to enter the guardband
void shared_fntick_sml(entity_t *_pself)
{
	entity_t& self = *_pself;

	// fetch x,y position offset from sintable
	s32 x = sintab32[self.wx & 8191];
	s32 y = sintab32[self.wy & 8191];

	// advance positions in sintable
	self.wx += self.vx;
	self.wy += self.vy;

	// assign position, relative to viewport
	self.rx = g_viewport_worldx + 160 - self.ox + (x >> 24);
	self.ry = g_viewport_worldy + 120 - self.oy + (y >> 24);
}

// tick function for bigger objects with occlusion maps
// this keeps them out of the guardband until occlusion maps can be clipped against the map bounds (todo)
void shared_fntick_big(entity_t *_pself)
{
	entity_t& self = *_pself;

	// fetch x,y position offset from sintable
	s32 x = sintab32[self.wx & 8191];
	s32 y = sintab32[self.wy & 8191];

	// advance positions in sintable
	self.wx += self.vx;
	self.wy += self.vy;

	// assign position, relative to viewport
	self.rx = g_viewport_worldx + 160 - self.ox + (x >> 24);
	self.ry = g_viewport_worldy + 120 - self.oy + (y >> 25);
}

