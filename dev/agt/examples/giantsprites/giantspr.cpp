//----------------------------------------------------------------------------------------------------------------------
//	tutorial: Giant Sprites (composite sprites) with and without occlusion maps
//----------------------------------------------------------------------------------------------------------------------
//	controls: none
//----------------------------------------------------------------------------------------------------------------------
//	notes:
//	+	EMS/EMX sprites wider than 32 pixels must be generated with the -emc switch ('composite' type).
//	+	composite sprites must not use the EMSPRQ/EMXSPRQ fastpath drawing modes. use only EMSPR/EMXSPR.
//	+	x-clipping of large sprites is achieved using a larger x-guardband, configured to 64 in the playfield
//		EMX sprites must be cut with -emgx 64 to ensure the generated files match the guardband size.
//	+	occlusion maps are generated by adding the -ocm switch and only works for composite sprites (-emc)
//	+	sprites generated with -ocm will only refresh properly when the playfield has PFA_OcclusionMaps attribute
//	+	occlusion maps can only be used with single-layer, 16x16 tile backgrounds.
//	+	occlusion maps use dirty tile states to refresh the footprint of the sprites using them. this means
//		overlapping sprites will only refresh the tiles below them once.
//	+	occlusion maps are inefficient for moderate to small sprites. they can provide savings for very large
//		sprites with a regular silhouette, few holes. especially if multiple such objects overlap.
//	+	further savings can be achieved by using EntityOccludeVisible to eliminate the opaque interiors of
//		sprites from their refresh footprint. this provides the most gain if the sprite is stationary or 
//		moving very slowly.
//	+	when using EntityOccludeVisible, note that opaque areas of such sprites will combine, further increasing
//		gains when objects overlap.
//
//	additional:

//----------------------------------------------------------------------------------------------------------------------

